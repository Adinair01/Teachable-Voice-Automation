package com.tva.teachable.replay

import com.tva.teachable.a11y.LiveTree
import com.tva.teachable.core.FlowJson
import com.tva.teachable.core.UiNode
import kotlinx.coroutines.runBlocking
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Part 0, phone half: "a replay uses the values just asked for, never the taught ones". The flows here are not written
 * by hand — they are what the backend's generalise() learned from the recorded demonstrations, with the values its
 * slot pipeline produced for each later command (backend test/fixtures, regenerated by scripts/part0-fixture.mjs and
 * checked for drift by test/part0Chain.test.js). Each test asserts what is TYPED and TAPPED.
 */
class ReplayChainTest {
    private val fixture = JSONObject(javaClass.getResource("/part0/flows.json")!!.readText())
    private val fast = ReplayConfig(waitMs = 60, retryMs = 30, pollMs = 10, settleMs = 30, scrollTries = 1)

    private companion object {
        /** The phone's home screen, before the app is launched. */
        val LAUNCHER = LiveTree(listOf(UiNode(0, 0, "com.android.launcher", "", "Home", "", "", "", false, false, false, false)), emptyList())
    }

    private fun slots(o: JSONObject) = o.getJSONObject("slots").let { s -> s.keys().asSequence().associateWith { s.getString(it) } }

    /** Nodes from rows of (depth, id, text, desc, clickable, editable). */
    private fun nodes(pkg: String, rows: List<List<Any>>) = rows.mapIndexed { i, r ->
        UiNode(i, r[0] as Int, pkg, r[1] as String, r[2] as String, r[3] as String, "", "0 0 10 10", r[4] as Boolean, r[5] as Boolean, false, false)
    }

    /** A calculator: digit keys, + = and Clear, and a display showing what was entered. */
    private class Calculator : Device {
        val pressed = ArrayList<String>()
        private var display = ""
        private var open = false
        override fun tree(): LiveTree {
            if (!open) return LAUNCHER
            val p = "com.coloros.calculator"
            val rows = mutableListOf<List<Any>>(listOf(0, "", "", "", false, false), listOf(1, "$p:id/display", display, "", false, false),
                listOf(1, "$p:id/clr", "", "Clear", true, false), listOf(1, "$p:id/op_add", "", "Add", true, false), listOf(1, "$p:id/eq", "", "Equals", true, false))
            for (d in 0..9) rows += listOf(1, "$p:id/digit_$d", "$d", "", true, false)
            return LiveTree(rows.mapIndexed { i, r -> UiNode(i, r[0] as Int, p, r[1] as String, r[2] as String, r[3] as String, "", "0 0 10 10", r[4] as Boolean, false, false, false) }, emptyList())
        }
        override fun tap(tree: LiveTree, node: UiNode): Boolean {
            val key = node.text.ifBlank { node.contentDesc }
            pressed += key
            display = when (key) { "Clear" -> ""; "Add" -> "$display+"; "Equals" -> display; else -> display + key }
            return true
        }
        override fun launch(packageName: String): Boolean { open = true; return true }
        override fun type(tree: LiveTree, node: UiNode, value: String) = false
        override fun scroll(tree: LiveTree) = false
        override fun back() = true
    }

    @Test fun `calculator taught 5+2 - 7+9, 100+1 and 5+2 press exactly the keys asked for`() = runBlocking {
        val calc = fixture.getJSONObject("calculator")
        val flow = FlowJson.parse(calc.getJSONObject("flow").toString())
        val replays = calc.getJSONArray("replays")
        for (k in 0 until replays.length()) {
            val r = replays.getJSONObject(k)
            val keys = r.getJSONArray("keys").let { a -> (0 until a.length()).map { a.getString(it) } }
            val device = Calculator()
            val result = Replayer(device, cfg = fast).run(flow, slots(r))
            assertTrue("${r.getString("said")}: ${result.steps}", result.success)
            val want = listOf("Clear") + keys[0].map { it.toString() } + "Add" + keys[1].map { it.toString() } + "Equals"
            assertEquals(r.getString("said"), want, device.pressed)
        }
    }

    /** Zomato as screens: home -> search -> restaurant -> menu search -> add sheet -> cart. Records what is typed and added. */
    private inner class Zomato : Device {
        val typed = ArrayList<String>()
        var added: String? = null
        private var screen = "launcher"
        private var field = ""
        private val z = "com.application.zomato"
        private val dishes = listOf("Double Cheese Margherita Pizza" to 249, "Margherita Pizza" to 114, "Farmhouse Pizza" to 279)
        private var built: List<UiNode> = emptyList()

        override fun tree(): LiveTree {
            if (screen == "launcher") return LAUNCHER
            val r = mutableListOf<List<Any>>(listOf(0, "", "", "", false, false))
            when (screen) {
                "home" -> r += listOf(1, "$z:id/search_bar_view_flipper", "Search \"comfort food\"", "", true, false)
                "search" -> {
                    r += listOf(1, "$z:id/edittext", field, "", true, true)
                    if (field.isNotEmpty()) for (name in listOf("Domino's Pizza", "Pizza Hut", "Domino's Pizza")) {
                        r += listOf(1, "", "", "", true, false); r += listOf(2, "", name, "", false, false)
                    }
                }
                "restaurant", "menuSearch" -> {
                    r += listOf(1, "", "Domino's Pizza", "", false, false)
                    r += listOf(1, "$z:id/menu_search", "", "Search in Domino's Pizza", true, false)
                    if (screen == "menuSearch") {
                        r += listOf(1, "$z:id/edittext", field, "", true, true)
                        r += listOf(1, "", "", "", false, false) // the results list
                        for ((name, price) in dishes.filter { (n, _) -> field.isNotEmpty() && n.contains(field.split(" ").first(), true) }) {
                            r += listOf(2, "", "", "", false, false)
                            r += listOf(3, "$z:id/dish_name", "", name, false, false)
                            r += listOf(3, "", "₹$price", "", false, false)
                            r += listOf(3, "$z:id/text_view_title", "", "ADD", true, false)
                        }
                    }
                }
                "sheet" -> {
                    r += listOf(1, "", added.orEmpty(), "", false, false)
                    r += listOf(1, "$z:id/button", "Add item ₹${dishes.first { it.first == added }.second}", "", true, false)
                }
                "menu" -> { r += listOf(1, "", "", "1 item added", false, false); r += listOf(1, "", "", "Continue", true, false) }
                "cart" -> { r += listOf(1, "", added.orEmpty(), "", false, false); r += listOf(1, "", "Bill details", "", false, false) }
            }
            built = nodes(z, r)
            return LiveTree(built, emptyList())
        }

        override fun tap(tree: LiveTree, node: UiNode): Boolean {
            val caption = node.text.ifBlank { node.contentDesc }
            when {
                screen == "home" && node.resourceId.endsWith("search_bar_view_flipper") -> { screen = "search"; field = "" }
                screen == "search" -> { screen = "restaurant"; field = "" }
                node.resourceId.endsWith("menu_search") -> { screen = "menuSearch"; field = "" }
                caption == "ADD" -> {
                    // The dish is the one named in the same row: the node just before its price.
                    added = tree.nodes.subList(0, node.index).last { it.resourceId.endsWith("dish_name") }.contentDesc
                    screen = "sheet"
                }
                screen == "sheet" -> screen = "menu"
                caption == "Continue" -> screen = "cart"
            }
            return true
        }
        override fun type(tree: LiveTree, node: UiNode, value: String): Boolean { if (value.isNotEmpty()) typed += value; field = value; return true }
        override fun launch(packageName: String): Boolean { screen = "home"; return true }
        override fun scroll(tree: LiveTree) = false
        override fun back() = true
    }

    private fun zomato(which: String, wantTyped: List<String>, wantAdded: String) = runBlocking {
        val case = fixture.getJSONObject(which)
        val flow = FlowJson.parse(case.getJSONObject("flow").toString())
        val device = Zomato()
        val r = Replayer(device, cfg = fast).run(flow, slots(case.getJSONObject("replay")))
        assertTrue(r.steps.toString(), r.success)
        assertEquals("what was typed into the search boxes", wantTyped, device.typed)
        assertEquals("what was added", wantAdded, device.added)
    }

    @Test fun `zomato taught Margherita - "order a Farmhouse" types Farmhouse and adds Farmhouse`() =
        zomato("margheritaTaught", listOf("Domino's", "Farmhouse pizza"), "Farmhouse Pizza")

    @Test fun `zomato taught Farmhouse - "order a Margherita" types Margherita and adds Margherita, not the look-alike listed first`() =
        zomato("farmhouseTaught", listOf("Domino's", "Margherita pizza"), "Margherita Pizza")
}
